//! `mayfly-fake-registry` (test plane): an HTTPS OCI registry serving synthetic Tart images, so
//! a process test can have `mayflyd` pull, verify and materialise an image (VER-09).
//!
//! `mayflyd`'s data plane fetches an image's raw manifest by digest over HTTPS itself, trusting
//! only the operating system's roots, before it asks Tart to pull (ADR 0087 decision 7); so no
//! process test could place an image before this crate. It serves the subset of the OCI
//! distribution API that a pull by digest reads, from its own code (D11: it imports no
//! workspace crate, so the image store and this oracle cannot agree by construction):
//!
//! - `GET`/`HEAD /v2/`: `200 {}`, the API's version check;
//! - `GET`/`HEAD /v2/<name>/manifests/<reference>`: the published manifest's exact bytes, its
//!   `mediaType` as `Content-Type` and its digest as `Docker-Content-Digest`;
//! - `GET`/`HEAD /v2/<name>/blobs/<digest>`: a blob the published image names;
//! - anything else: `404` with an OCI error body (`MANIFEST_UNKNOWN`, `BLOB_UNKNOWN`,
//!   `NAME_UNKNOWN`), or `405` for another method.
//!
//! No credentials are asked for (an anonymous pull with no token challenge); the token flow is
//! pinned by `mayfly-adapter-tart`'s own tests.
//!
//! **Independent** (D11, ADR 0012): no workspace crate is imported, and no production crate
//! imports this one; it is a dev-dependency of the tests that need it.
//!
//! **TLS with a CA made at run time** ([`FakeRegistry::start`]): a fresh certificate authority
//! and a server certificate for `127.0.0.1` and `localhost`, generated by rcgen for each
//! registry and never written to the repository, so no key material is ever committed and every
//! test trusts only its own registry. A test hands [`FakeRegistry::ca_pem`] to the client it
//! starts: to `mayflyd` as a PEM file named by `SSL_CERT_FILE` in the daemon's environment.
//!
//! **Why `SSL_CERT_FILE`** (ver §7.5): the data plane trusts the operating system's roots only,
//! and on Linux the platform verifier loads them through rustls-native-certs, which reads that
//! variable (OpenSSL's convention). So `mayflyd` trusts a test's CA with no production code,
//! configuration key or test-only build; the variable is not on the child allowlist and need not
//! be. macOS's verifier reads the keychain alone, which a test cannot change without the owner,
//! so the placement tests under `mayflyd` are Linux-only; this crate's own tests run anywhere.
//!
//! **The same bytes for Tart** ([`seed_tart_home`]): `mayfly-fake-tart` never reaches a network;
//! its `pull` serves what a lab seeded under `TART_HOME/registry/`. Seeding it with the image
//! this registry serves makes the fake's pull and the data plane's HTTPS fetch read identical
//! manifests and blobs, as one real registry would serve both.
//!
//! Pinned by `tests/registry.rs` and the unit tests of [`image`].

