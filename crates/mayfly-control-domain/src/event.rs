//! Events: immutable, versioned facts (plan §5.3, fnd §6.1), and the generic codec hook the
//! journal adapter and the golden harness drive.
//!
//! The codec is written against `serde`'s `Serializer`/`Deserializer` traits so this pure
//! crate names no format; the payload is the event struct's own serde form, and the kind
//! (`EVENT_TYPE`, `SCHEMA_VERSION`) travels beside it (the journal's `type` and
//! `schema_version` columns, the fixture's path).

use std::fmt;

use serde::de::DeserializeOwned;
use serde::{Deserializer, Serialize, Serializer};

/// One event type at one schema version: a past-tense, `#[non_exhaustive]` struct.
///
/// `EVENT_TYPE` is `snake_case` and never renamed; a shape change is a new version (read
/// through an upcaster) or a new type (fnd §6.5). The golden harness checks both constants
/// (`mayfly_testkit::golden`).
pub trait DomainEvent: Serialize + DeserializeOwned {
    /// The stable name, `[a-z][a-z0-9_]*`.
    const EVENT_TYPE: &'static str;
    /// The payload version, from 1.
    const SCHEMA_VERSION: u32;
}

/// The `(type, version)` pair that identifies a payload's shape.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct EventKind {
    /// [`DomainEvent::EVENT_TYPE`].
    pub event_type: &'static str,
    /// [`DomainEvent::SCHEMA_VERSION`].
    pub schema_version: u32,
}

impl EventKind {
    /// The kind of `E`.
    #[must_use]
    pub const fn of<E: DomainEvent>() -> Self {
        Self {
            event_type: E::EVENT_TYPE,
            schema_version: E::SCHEMA_VERSION,
        }
    }
}

impl fmt::Display for EventKind {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}/v{}", self.event_type, self.schema_version)
    }
}

/// Why a payload did not decode.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DecodeError<E> {
    /// No registered event has this kind: the reader cannot prove it understands the journal,
    /// so the daemon enters safe mode (fnd §6.8). Decoding never guesses (pinned by the
    /// testkit's `should_refuse_unknown_kind_when_type_or_version_is_not_registered`).
    UnknownKind {
        /// The stored type.
        event_type: String,
        /// The stored version.
        schema_version: u32,
    },
    /// The kind is known but the payload does not have its shape.
    Malformed(E),
}

impl<E: fmt::Display> fmt::Display for DecodeError<E> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::UnknownKind {
                event_type,
                schema_version,
            } => write!(f, "unknown event kind {event_type}/v{schema_version}"),
            Self::Malformed(e) => write!(f, "malformed event payload: {e}"),
        }
    }
}

impl<E: fmt::Debug + fmt::Display> std::error::Error for DecodeError<E> {}

/// An aggregate's events: an enum with one variant per current event struct, plus the legacy
/// versions it still reads. Generated by [`crate::event_set!`]; not implemented by hand.
pub trait EventSet: Sized + Clone + fmt::Debug + PartialEq {
    /// The kinds this set writes: one current version per event type.
    const KINDS: &'static [EventKind];
    /// Older kinds this set still reads, each through its upcaster into a current event.
    const LEGACY_KINDS: &'static [EventKind];

    /// The kind this event is written as.
    fn kind(&self) -> EventKind;

    /// Serialises the payload (the event struct alone, not its kind).
    ///
    /// # Errors
    /// Whatever the serializer reports.
    fn encode<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error>;

    /// Deserialises a payload stored under `(event_type, schema_version)`, upcasting a legacy
    /// version on load (never on write, fnd §6.5).
    ///
    /// # Errors
    /// [`DecodeError::UnknownKind`] for a kind not in [`EventSet::KINDS`] or
    /// [`EventSet::LEGACY_KINDS`]; [`DecodeError::Malformed`] for a payload of the wrong shape.
    fn decode<'de, D: Deserializer<'de>>(
        event_type: &str,
        schema_version: u32,
        deserializer: D,
    ) -> Result<Self, DecodeError<D::Error>>;

    /// The traced shape of the payload stored under `kind`, current or legacy; `None` for a
    /// kind this set does not read. The golden harness requires every field and variant of it
    /// to appear in some committed sample ([`crate::shape`]), and fails a registered kind whose
    /// shape is `None` (`mayfly_testkit::golden`, pinned by its
    /// `should_fail_when_the_event_set_has_no_shape_for_a_registered_kind`).
    fn shape(kind: EventKind) -> Option<crate::shape::Shape>;
}

/// Declares an aggregate's event enum and its [`EventSet`] codec.
///
/// ```
/// use mayfly_control_domain::{DomainEvent, EventSet, event_set};
/// use serde::{Deserialize, Serialize};
///
/// #[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
/// #[non_exhaustive]
/// pub struct LampLit { pub watts: u32 }
/// impl DomainEvent for LampLit {
///     const EVENT_TYPE: &'static str = "lamp_lit";
///     const SCHEMA_VERSION: u32 = 2;
/// }
///
/// /// Version 1 carried no wattage.
/// #[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
/// pub struct LampLitV1 {}
/// impl DomainEvent for LampLitV1 {
///     const EVENT_TYPE: &'static str = "lamp_lit";
///     const SCHEMA_VERSION: u32 = 1;
/// }
///
/// fn upcast_lamp_lit_v1(_old: LampLitV1) -> LampEvent {
///     LampEvent::Lit(LampLit { watts: 0 })
/// }
///
/// event_set! {
///     /// What happened to a lamp.
///     pub enum LampEvent {
///         /// It was lit.
///         Lit(LampLit),
///     }
///     legacy {
///         LampLitV1 => upcast_lamp_lit_v1,
///     }
/// }
///
/// assert_eq!(LampEvent::KINDS.len(), 1);
/// assert_eq!(LampEvent::LEGACY_KINDS.len(), 1);
/// ```
///
/// The `legacy` block is the upcaster hook: each older struct is decoded, then mapped by a
/// pure `fn(Old) -> Enum` that must land on the current version of the same type. The golden
/// harness requires every version from 1 to the current one to be registered, a
/// `v<n>[.<slug>].expected.json` beside each legacy sample, and the upcast's kind to be that
/// current version (`mayfly_testkit::golden`, pinned by its
/// `should_fail_when_upcast_lands_on_another_kind`).
#[macro_export]
macro_rules! event_set {
    (
        $(#[$meta:meta])*
        $vis:vis enum $name:ident {
            $( $(#[$vmeta:meta])* $variant:ident($event:ty) ),+ $(,)?
        }
        $( legacy { $( $old:ty => $upcast:path ),+ $(,)? } )?
    ) => {
        $(#[$meta])*
        #[derive(Debug, Clone, PartialEq)]
        $vis enum $name {
            $( $(#[$vmeta])* $variant($event), )+
        }

        impl $crate::event::EventSet for $name {
            const KINDS: &'static [$crate::event::EventKind] =
                &[ $( $crate::event::EventKind::of::<$event>(), )+ ];
            const LEGACY_KINDS: &'static [$crate::event::EventKind] =
                &[ $($( $crate::event::EventKind::of::<$old>(), )+)? ];

            fn kind(&self) -> $crate::event::EventKind {
                match self {
                    $( Self::$variant(_) => $crate::event::EventKind::of::<$event>(), )+
                }
            }

            fn encode<S: $crate::__serde::Serializer>(
                &self,
                serializer: S,
            ) -> ::core::result::Result<S::Ok, S::Error> {
                match self {
                    $( Self::$variant(event) =>
                        $crate::__serde::Serialize::serialize(event, serializer), )+
                }
            }

            fn decode<'de, D: $crate::__serde::Deserializer<'de>>(
                event_type: &str,
                schema_version: u32,
                deserializer: D,
            ) -> ::core::result::Result<Self, $crate::event::DecodeError<D::Error>> {
                $(
                    if event_type == <$event as $crate::event::DomainEvent>::EVENT_TYPE
                        && schema_version == <$event as $crate::event::DomainEvent>::SCHEMA_VERSION
                    {
                        return <$event as $crate::__serde::Deserialize>::deserialize(deserializer)
                            .map(Self::$variant)
                            .map_err($crate::event::DecodeError::Malformed);
                    }
                )+
                $($(
                    if event_type == <$old as $crate::event::DomainEvent>::EVENT_TYPE
                        && schema_version == <$old as $crate::event::DomainEvent>::SCHEMA_VERSION
                    {
                        return <$old as $crate::__serde::Deserialize>::deserialize(deserializer)
                            .map($upcast)
                            .map_err($crate::event::DecodeError::Malformed);
                    }
                )+)?
                let _ = deserializer;
                ::core::result::Result::Err($crate::event::DecodeError::UnknownKind {
                    event_type: ::std::string::String::from(event_type),
                    schema_version,
                })
            }

            fn shape(
                kind: $crate::event::EventKind,
            ) -> ::core::option::Option<$crate::shape::Shape> {
                $(
                    if kind == $crate::event::EventKind::of::<$event>() {
                        return ::core::option::Option::Some($crate::shape::trace::<$event>());
                    }
                )+
                $($(
                    if kind == $crate::event::EventKind::of::<$old>() {
                        return ::core::option::Option::Some($crate::shape::trace::<$old>());
                    }
                )+)?
                ::core::option::Option::None
            }
        }
    };
}
