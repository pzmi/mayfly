//! `ARCH-single-append` (foundation.md sections 3.3 and 6.3, `doc/event-store.md` §3.7):
//! `AggregateStore::save` is the only caller of `Journal::append`, so every write the control
//! plane makes goes through the epoch check, the receipt, the derived event ids and the
//! after-commit kick, in that order. A second caller would write units nothing checked.
//!
//! In every crate of the control plane and of `[planes] both` (production and test code), a
//! call is refused when it is:
//!
//! - a method call `.append(x)` with one argument that is neither `&mut ..` (`Vec::append`,
//!   `BTreeMap::append`) nor a literal (`OpenOptions::append(true)`): method calls are not
//!   type-resolved, so the shape of the argument tells a journal append from the collections'
//!   (a unit of work is passed by value);
//! - a path call `P::append(r, ..)` (two segments or more, or a qualified `<T as P>::append`)
//!   whose first argument, the receiver, is not `&mut ..`: the fully qualified form by any name,
//!   `Journal::append(&j, u)`, `MemoryJournal::append(&j, u)`, a generic `T::append(j, u)`,
//!   `Self::append(self, u)` or an alias (`use Journal as J; J::append(j, u)`), which no
//!   name test could tell apart; `Vec::append(&mut a, &mut b)` passes;
//! - a path `..::append` that is not called (`let f = Journal::append;`, `.map(T::append)`):
//!   a function value reaches the journal without a visible call;
//! - the same forms written inside a macro's tokens (`assert!(j.append(u).is_ok())`,
//!   `assert!(Journal :: append(&j, u).is_ok())`), found by scanning for `.` `append` `(..)` and
//!   `::` `append`.
//!
//! Allowed, and only there:
//!
//! - the bodies of `save` and `settle` (its step 5, split out for length) in an
//!   `impl .. AggregateStore ..` block of `mayfly-control`;
//! - an `impl .. Journal for ..` block (one journal wrapping another, an adapter delegating to
//!   its writer) in a journal adapter crate (`mayfly-adapter-*`), in the test kit
//!   (`mayfly-testkit`: the memory journal and its broken variants) or in test code (a file
//!   outside `src/`, a `#[cfg(test)]` or `#[test]` item): a production `impl Journal` anywhere
//!   else would be a second write path wearing the port's name;
//! - the journal contract suite, `crates/mayfly-testkit/src/contracts/`, and its own tests,
//!   `crates/mayfly-testkit/tests/journal_contract.rs` (the broken journals it must catch);
//! - a journal adapter's contract test files (`mayfly-adapter-*/tests/*_contract.rs`), which
//!   drive the adapter below the store as the suite does (JC-27, the frozen-schema case). Its
//!   other tests and `#[cfg(test)]` modules go through the store or the suite like any caller.
//!
//! What is not seen: a call through a trait object or function pointer obtained without naming
//! `append` (there is none to write: `Journal` is not object safe), and code generated by a
//! procedural macro. A renamed crate or directory makes an exemption lapse, so the rule then
//! fails closed rather than passing unchecked. Pinned by
//! `should_report_appends_outside_the_store_when_code_calls_one`,
//! `should_report_path_calls_by_any_name_when_the_receiver_is_not_mut`,
//! `should_allow_the_store_journals_and_collections_when_they_append`,
//! `should_refuse_a_production_journal_impl_when_outside_adapters_and_testkit` and the negative
//! fixtures `second-append-caller`, `append-ufcs-by-type`, `append-generic-path`,
//! `append-through-alias` and `append-path-in-macro`.

use proc_macro2::{Delimiter, TokenStream, TokenTree};
use syn::visit::{self, Visit};
use syn::{Expr, ExprCall, ExprMethodCall, ExprPath, ImplItemFn, ItemFn, ItemImpl, ItemMod, Macro};

use super::super::policy::Policy;
use super::super::report::{Diagnostic, Rule};
use super::{Facts, is_test_only};

/// The package whose `AggregateStore` may append.
const STORE_PACKAGE: &str = "mayfly-control";
/// The functions of `impl AggregateStore` that may append.
const STORE_FNS: &[&str] = &["save", "settle"];
/// The journal contract suite and its own tests, by path prefix.
const CONTRACT_PATHS: &[&str] = &[
    "crates/mayfly-testkit/src/contracts/",
    "crates/mayfly-testkit/tests/journal_contract.rs",
];
/// The prefix of the journal adapter crates.
const ADAPTER_PREFIX: &str = "mayfly-adapter-";
/// The test kit, whose journals may implement the port in production code.
const TESTKIT: &str = "mayfly-testkit";
/// The suffix of an adapter's contract test files.
const CONTRACT_TEST_SUFFIX: &str = "_contract.rs";

/// The diagnostics of this rule for one package.
pub fn check(facts: &Facts, policy: &Policy) -> Vec<Diagnostic> {
    let selected = policy
        .planes
        .control
        .iter()
        .chain(&policy.planes.both)
        .any(|name| *name == facts.package);
    if !selected {
        return Vec::new();
    }
    let adapter = facts.package.starts_with(ADAPTER_PREFIX);
    let prefix = if facts.dir.is_empty() {
        String::new()
    } else {
        format!("{}/", facts.dir)
    };
    let src = format!("{prefix}src/");
    let adapter_tests = format!("{prefix}tests/");
    let mut out = Vec::new();
    for (path, text) in &facts.sources {
        let contract = CONTRACT_PATHS.iter().any(|p| path.starts_with(p))
            || (adapter
                && path.starts_with(&adapter_tests)
                && path.ends_with(CONTRACT_TEST_SUFFIX));
        if contract {
            continue;
        }
        let Ok(file) = syn::parse_file(text) else {
            continue;
        };
        let test_file = !path.starts_with(&src) || is_test_only(&file.attrs);
        let mut scan = Scan {
            package: &facts.package,
            file: path,
            journal_impls: adapter || facts.package == TESTKIT,
            store: false,
            allowed: 0,
            tests: usize::from(test_file),
            out: &mut out,
        };
        scan.visit_file(&file);
    }
    out
}

struct Scan<'a> {
    package: &'a str,
    file: &'a str,
    /// Production `impl Journal` blocks are allowed in this package.
    journal_impls: bool,
    /// Inside an `impl .. AggregateStore ..` block of the store package.
    store: bool,
    /// Depth of allowed scopes being visited.
    allowed: usize,
    /// Depth of test-only scopes being visited (the file itself counts as one).
    tests: usize,
    out: &'a mut Vec<Diagnostic>,
}

impl Scan<'_> {
    fn report(&mut self, line: usize, what: &str) {
        if self.allowed > 0 {
            return;
        }
        self.out.push(Diagnostic::new(
            Rule::SingleAppend,
            format!(
                "{} calls {what} outside AggregateStore::save: only the store writes the journal, so every unit goes through its epoch check, receipt and derived ids (foundation.md section 6.3)",
                self.package
            ),
            format!("{}:{line}", self.file),
        ));
    }

    fn allow(&mut self, visit: impl FnOnce(&mut Self)) {
        self.allowed += 1;
        visit(self);
        self.allowed -= 1;
    }

    fn in_test(&mut self, test: bool, visit: impl FnOnce(&mut Self)) {
        self.tests += usize::from(test);
        visit(self);
        self.tests -= usize::from(test);
    }
}

fn last_segment(path: &syn::Path) -> String {
    path.segments
        .last()
        .map(|s| s.ident.to_string())
        .unwrap_or_default()
}

/// Whether `arg` is what a journal append takes: not `&mut ..` and not a literal.
fn unit_like(arg: &Expr) -> bool {
    !by_mut(arg) && !matches!(arg, Expr::Lit(_))
}

fn by_mut(arg: &Expr) -> bool {
    matches!(arg, Expr::Reference(r) if r.mutability.is_some())
}

/// A path that ends in `append` and names more than the bare function: two segments or more,
/// or a qualified self type.
fn qualified_append(expr: &ExprPath) -> bool {
    last_segment(&expr.path) == "append" && (expr.qself.is_some() || expr.path.segments.len() >= 2)
}

fn line_of(expr: &ExprPath) -> usize {
    expr.path
        .segments
        .last()
        .map_or(0, |s| s.ident.span().start().line)
}

/// Whether macro-token arguments begin with `& mut`.
fn tokens_by_mut(args: &[TokenTree]) -> bool {
    matches!(
        (args.first(), args.get(1)),
        (Some(TokenTree::Punct(p)), Some(TokenTree::Ident(m))) if p.as_char() == '&' && m == "mut"
    )
}

/// The appends in macro tokens: `. append ( .. )` with the argument test of [`unit_like`] (a
/// leading `& mut` or a single literal is a collection's or a file's append), and `:: append`
/// either uncalled or called with a first argument that is not `& mut ..`.
fn appends_in_tokens(tokens: TokenStream, lines: &mut Vec<usize>) {
    let trees: Vec<TokenTree> = tokens.into_iter().collect();
    let punct =
        |i: usize, c: char| matches!(trees.get(i), Some(TokenTree::Punct(p)) if p.as_char() == c);
    for (i, tree) in trees.iter().enumerate() {
        if let TokenTree::Group(group) = tree {
            appends_in_tokens(group.stream(), lines);
        }
        let TokenTree::Ident(ident) = tree else {
            continue;
        };
        if ident != "append" {
            continue;
        }
        let dotted = i > 0 && punct(i - 1, '.');
        let pathed = i > 1 && punct(i - 1, ':') && punct(i - 2, ':');
        let call = match trees.get(i + 1) {
            Some(TokenTree::Group(g)) if g.delimiter() == Delimiter::Parenthesis => Some(g),
            _ => None,
        };
        let args: Vec<TokenTree> = call
            .map(|g| g.stream().into_iter().collect())
            .unwrap_or_default();
        let hit = if dotted {
            let literal = args.len() == 1 && matches!(args[0], TokenTree::Literal(_));
            call.is_some() && !args.is_empty() && !tokens_by_mut(&args) && !literal
        } else {
            pathed && !tokens_by_mut(&args)
        };
        if hit {
            lines.push(ident.span().start().line);
        }
    }
}

impl<'ast> Visit<'ast> for Scan<'_> {
    fn visit_item_mod(&mut self, module: &'ast ItemMod) {
        self.in_test(is_test_only(&module.attrs), |scan| {
            visit::visit_item_mod(scan, module);
        });
    }

    fn visit_item_fn(&mut self, item: &'ast ItemFn) {
        self.in_test(is_test_only(&item.attrs), |scan| {
            visit::visit_item_fn(scan, item);
        });
    }

    fn visit_item_impl(&mut self, item: &'ast ItemImpl) {
        let test = is_test_only(&item.attrs);
        self.in_test(test, |scan| {
            let journal_impl = item
                .trait_
                .as_ref()
                .is_some_and(|(path, _)| last_segment(path) == "Journal");
            if journal_impl && (scan.journal_impls || scan.tests > 0) {
                scan.allow(|scan| visit::visit_item_impl(scan, item));
                return;
            }
            if journal_impl {
                let line = item.impl_token.span.start().line;
                scan.report(line, "`impl Journal` (a production journal outside the adapters and the test kit)");
            }
            let store = item.trait_.is_none()
                && scan.package == STORE_PACKAGE
                && matches!(&*item.self_ty, syn::Type::Path(p) if last_segment(&p.path) == "AggregateStore");
            let outer = scan.store;
            scan.store = store;
            visit::visit_item_impl(scan, item);
            scan.store = outer;
        });
    }

    fn visit_impl_item_fn(&mut self, item: &'ast ImplItemFn) {
        let test = is_test_only(&item.attrs);
        self.in_test(test, |scan| {
            if scan.store && STORE_FNS.iter().any(|f| item.sig.ident == f) {
                scan.allow(|scan| visit::visit_impl_item_fn(scan, item));
            } else {
                visit::visit_impl_item_fn(scan, item);
            }
        });
    }

    fn visit_expr_method_call(&mut self, call: &'ast ExprMethodCall) {
        if call.method == "append" && call.args.len() == 1 && call.args.iter().all(unit_like) {
            self.report(call.method.span().start().line, "`.append(..)`");
        }
        visit::visit_expr_method_call(self, call);
    }

    fn visit_expr_call(&mut self, call: &'ast ExprCall) {
        let Expr::Path(func) = &*call.func else {
            visit::visit_expr_call(self, call);
            return;
        };
        if !qualified_append(func) {
            visit::visit_expr_call(self, call);
            return;
        }
        if !call.args.first().is_some_and(by_mut) {
            self.report(line_of(func), "`..::append(..)` by path");
        }
        for arg in &call.args {
            self.visit_expr(arg);
        }
    }

    fn visit_expr_path(&mut self, expr: &'ast ExprPath) {
        if qualified_append(expr) {
            self.report(line_of(expr), "`..::append` as a value");
        }
        visit::visit_expr_path(self, expr);
    }

    fn visit_macro(&mut self, mac: &'ast Macro) {
        let mut lines = Vec::new();
        appends_in_tokens(mac.tokens.clone(), &mut lines);
        for line in lines {
            self.report(line, "`append` in a macro's tokens");
        }
        visit::visit_macro(self, mac);
    }
}

#[cfg(test)]
mod tests {
    use super::super::testing::{facts_for, policy, rendered};
    use super::*;

    /// The facts of `package` with `lib` as `src/lib.rs` and `others` as further files, by path
    /// relative to the package (a `tests/` file is not reached from the library root).
    fn package(name: &str, lib: &str, others: &[(&str, &str)]) -> Facts {
        let mut facts = facts_for(name, &[("src/lib.rs", lib)]);
        for (path, text) in others {
            facts
                .sources
                .insert(format!("crates/{name}/{path}"), (*text).to_owned());
        }
        facts
    }

    fn lines(diagnostics: &[Diagnostic]) -> Vec<String> {
        rendered(diagnostics)
            .iter()
            .map(|d| {
                d.rsplit(':')
                    .next()
                    .unwrap_or("")
                    .trim_end_matches(')')
                    .to_owned()
            })
            .collect()
    }

    #[test]
    fn should_report_appends_outside_the_store_when_code_calls_one() {
        // given
        let source = "pub trait Journal { fn append(&self, u: u8); }\npub fn bypass<J: Journal>(j: &J) {\n    j.append(1 + 1);\n    <J as Journal>::append(j, 2);\n    let f = Journal::append;\n    assert!(matches!(j.append(unit()), ()));\n}\nfn unit() -> u8 { 0 }\npub struct Other;\nimpl Other {\n    pub fn save<J: Journal>(j: &J) { j.append(unit()); }\n}\n";

        // when
        let got = check(
            &facts_for("mayfly-control", &[("src/lib.rs", source)]),
            &policy(),
        );

        // then
        assert_eq!(lines(&got), ["3", "4", "5", "6", "11"], "{got:?}");
        assert!(
            rendered(&got)[0].starts_with("ARCH-single-append"),
            "{got:?}"
        );
    }

    #[test]
    fn should_report_path_calls_by_any_name_when_the_receiver_is_not_mut() {
        // given
        let source = "use crate::Journal as J;\npub trait Journal { fn append(&self, u: u8); }\npub struct MemoryJournal;\npub fn bypass<T: Journal>(m: &MemoryJournal, t: &T) {\n    MemoryJournal::append(m, 1);\n    T::append(t, 2);\n    J::append(t, 3);\n    assert!(Journal :: append(t, 4) == ());\n    [1].iter().for_each(|_| { let _ = T::append; });\n    assert_eq!(vec![MemoryJournal::append(m, 5)], vec![]);\n}\npub struct Wrap;\nimpl Wrap {\n    fn append(&self, _: u8) {}\n    pub fn go(&self) { Self::append(self, 6); }\n}\npub fn collections(mut a: Vec<u8>, mut b: Vec<u8>) {\n    Vec::append(&mut a, &mut b);\n    assert!({ Vec::append(&mut a, &mut b); true });\n}\n";

        // when
        let got = check(
            &facts_for("mayfly-control", &[("src/lib.rs", source)]),
            &policy(),
        );

        // then
        assert_eq!(
            lines(&got),
            ["5", "6", "7", "8", "9", "10", "15"],
            "{got:?}"
        );
    }

    #[test]
    fn should_allow_the_store_journals_and_collections_when_they_append() {
        // given
        let source = "pub trait Journal { fn append(&self, u: u8); }\npub struct AggregateStore<J>(J);\nimpl<J: Journal> AggregateStore<J> {\n    pub fn save(&self) { self.0.append(unit()); self.settle(); }\n    fn settle(&self) { self.0.append(unit()); }\n}\nfn unit() -> u8 { 0 }\npub fn collections(mut a: Vec<u8>, mut b: Vec<u8>, o: &mut std::fs::OpenOptions) {\n    a.append(&mut b);\n    o.append(true);\n    assert!(a.is_empty() || { a.append(&mut b); true });\n}\n#[cfg(test)]\nmod tests {\n    pub struct Wrapper<J>(J);\n    impl<J: super::Journal> super::Journal for Wrapper<J> {\n        fn append(&self, u: u8) { self.0.append(u) }\n    }\n}\n";
        let adapter = "pub trait Journal { fn append(&self, u: u8); }\npub struct Sqlite;\nimpl Journal for Sqlite {\n    fn append(&self, u: u8) { inner::append(self, u) }\n}\nmod inner { pub fn append(_: &super::Sqlite, _: u8) {} }\n";
        let contract = "pub fn jc27<J: Journal>(j: &J) { j.append(1 + 1); }\npub trait Journal { fn append(&self, u: u8); }\n";
        let testkit = "pub trait Journal { fn append(&self, u: u8); }\npub struct Memory;\nimpl Journal for Memory {\n    fn append(&self, u: u8) { Self::append(self, u) }\n}\n";

        // when
        let store = check(
            &facts_for("mayfly-control", &[("src/lib.rs", source)]),
            &policy(),
        );
        let elsewhere = check(
            &facts_for("mayfly-control-domain", &[("src/lib.rs", source)]),
            &policy(),
        );
        let adapter = check(
            &package(
                "mayfly-adapter-sqlite",
                adapter,
                &[("tests/journal_contract.rs", contract)],
            ),
            &policy(),
        );
        let testkit = check(
            &facts_for("mayfly-testkit", &[("src/lib.rs", testkit)]),
            &policy(),
        );
        let data_plane = check(
            &facts_for(
                "mayfly-data",
                &[("src/lib.rs", "pub fn f(j: &u8) { j.append(1 + 1); }\n")],
            ),
            &policy(),
        );

        // then
        assert_eq!(rendered(&store), Vec::<String>::new());
        assert_eq!(rendered(&adapter), Vec::<String>::new());
        assert_eq!(rendered(&testkit), Vec::<String>::new());
        assert_eq!(rendered(&data_plane), Vec::<String>::new());
        assert_eq!(
            lines(&elsewhere),
            ["4", "5"],
            "save and settle are the store's only in mayfly-control: {elsewhere:?}"
        );
    }

    #[test]
    fn should_refuse_a_production_journal_impl_when_outside_adapters_and_testkit() {
        // given
        let wrapper = "pub trait Journal { fn append(&self, u: u8); }\npub struct Wrapper<J>(J);\nimpl<J: Journal> Journal for Wrapper<J> {\n    fn append(&self, u: u8) { self.0.append(u) }\n}\n";
        let adapter_tests = "pub fn f() {}\n#[cfg(test)]\nmod tests {\n    fn t<J: super::Journal>(j: &J, u: u8) { j.append(u); }\n}\npub trait Journal { fn append(&self, u: u8); }\n";
        let other_test = "pub fn t<J: Journal>(j: &J) { j.append(1 + 1); }\npub trait Journal { fn append(&self, u: u8); }\n";

        // when
        let composition = check(
            &facts_for("mayfly-composition", &[("src/lib.rs", wrapper)]),
            &policy(),
        );
        let adapter = check(
            &package(
                "mayfly-adapter-sqlite",
                adapter_tests,
                &[("tests/reopen.rs", other_test)],
            ),
            &policy(),
        );

        // then
        assert_eq!(lines(&composition), ["3", "4"], "{composition:?}");
        assert!(rendered(&composition)[0].contains("`impl Journal`"));
        assert_eq!(lines(&adapter), ["4", "1"], "{adapter:?}");
    }
}
